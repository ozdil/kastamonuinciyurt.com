const LANGUAGE_CONFIG = {
  tr: { name: "Türkçe", flag: "🇹🇷", dir: "ltr", code: "tr" },
  en: { name: "English", flag: "🇬🇧", dir: "ltr", code: "en" },
  ar: { name: "العربية", flag: "🇸🇦", dir: "rtl", code: "ar" },
  ru: { name: "Русский", flag: "🇷🇺", dir: "ltr", code: "ru" }
};

let currentLang = "tr";

/**
 * Retrieve nested translation value by key string, e.g. "hero.title"
 */
function getTranslation(lang, key) {
  const dict = I18N_DATA[lang] || I18N_DATA["tr"];
  const parts = key.split(".");
  let cur = dict;
  for (const p of parts) {
    if (cur && typeof cur === "object" && p in cur) {
      cur = cur[p];
    } else {
      // Fallback to Turkish if key missing
      let fallback = I18N_DATA["tr"];
      for (const fp of parts) {
        if (fallback && typeof fallback === "object" && fp in fallback) {
          fallback = fallback[fp];
        } else {
          return null;
        }
      }
      return fallback;
    }
  }
  return cur;
}

/**
 * Switch page language dynamically
 */
function setLanguage(lang) {
  if (!LANGUAGE_CONFIG[lang]) {
    lang = "tr";
  }
  currentLang = lang;
  try {
    localStorage.setItem("inci_user_lang", lang);
  } catch (e) {}

  const config = LANGUAGE_CONFIG[lang];
  const htmlEl = document.documentElement;

  // Set direction and lang attribute
  htmlEl.setAttribute("lang", lang);
  htmlEl.setAttribute("dir", config.dir);

  // Dynamic Arabic font loader
  if (lang === "ar") {
    if (!document.getElementById("cairo-arabic-font")) {
      const link = document.createElement("link");
      link.id = "cairo-arabic-font";
      link.rel = "stylesheet";
      link.href = "https://fonts.googleapis.com/css2?family=Cairo:wght@400;600;700;800;900&display=swap";
      document.head.appendChild(link);
    }
    document.body.classList.add("font-arabic");
  } else {
    document.body.classList.remove("font-arabic");
  }

  // Translate all data-i18n elements
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = getTranslation(lang, key);
    if (val !== null && typeof val === "string") {
      el.textContent = val;
    }
  });

  // Translate all data-i18n-html elements
  const htmlElements = document.querySelectorAll("[data-i18n-html]");
  htmlElements.forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    const val = getTranslation(lang, key);
    if (val !== null && typeof val === "string") {
      el.innerHTML = val;
    }
  });

  // Translate placeholders
  const placeholderElements = document.querySelectorAll("[data-i18n-placeholder]");
  placeholderElements.forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const val = getTranslation(lang, key);
    if (val !== null && typeof val === "string") {
      el.setAttribute("placeholder", val);
    }
  });

  // Translate select options
  const optionElements = document.querySelectorAll("[data-i18n-option]");
  optionElements.forEach((el) => {
    const key = el.getAttribute("data-i18n-option");
    const val = getTranslation(lang, key);
    if (val !== null && typeof val === "string") {
      el.textContent = val;
    }
  });

  // Update Language Switcher UI
  updateLanguageSwitcherUI(lang);

  // Dispatch custom event for any listeners
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang, config } }));
}

/**
 * Update Language Switcher UI elements (Desktop dropdown & Mobile buttons)
 */
function updateLanguageSwitcherUI(lang) {
  const config = LANGUAGE_CONFIG[lang];

  // Desktop active label
  const desktopActiveFlag = document.getElementById("lang-active-flag");
  const desktopActiveLabel = document.getElementById("lang-active-label");
  if (desktopActiveFlag) desktopActiveFlag.textContent = config.flag;
  if (desktopActiveLabel) desktopActiveLabel.textContent = lang.toUpperCase();

  // Mobile active label
  const mobileActiveFlag = document.getElementById("mobile-active-flag");
  const mobileActiveLabel = document.getElementById("mobile-active-label");
  if (mobileActiveFlag) mobileActiveFlag.textContent = config.flag;
  if (mobileActiveLabel) mobileActiveLabel.textContent = lang.toUpperCase();

  // Mobile active indicators
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const btnLang = btn.getAttribute("data-lang");
    if (btnLang === lang) {
      btn.classList.add("bg-rose-50", "text-rose-900", "font-bold", "border-rose-300");
      btn.classList.remove("text-stone-700", "border-pearl-200");
    } else {
      btn.classList.remove("bg-rose-50", "text-rose-900", "font-bold", "border-rose-300");
      btn.classList.add("text-stone-700", "border-pearl-200");
    }
  });
}

/**
 * Initialize i18n on page load
 */
function initI18n() {
  // Check URL param e.g. ?lang=en or ?lang=ar
  const urlParams = new URLSearchParams(window.location.search);
  const paramLang = urlParams.get("lang");

  // Check stored preference
  let savedLang = null;
  try {
    savedLang = localStorage.getItem("inci_user_lang");
  } catch (e) {}

  // Check browser language
  let browserLang = null;
  if (navigator.languages && navigator.languages.length > 0) {
    const primary = navigator.languages[0].toLowerCase();
    if (primary.startsWith("ar")) browserLang = "ar";
    else if (primary.startsWith("ru")) browserLang = "ru";
    else if (primary.startsWith("en")) browserLang = "en";
  }

  const initialLang = paramLang || savedLang || browserLang || "tr";
  setLanguage(initialLang);
}

// Auto-initialize when DOM is ready
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initI18n);
} else {
  initI18n();
}

// Expose functions globally
window.setLanguage = setLanguage;
window.getLanguage = () => currentLang;
window.I18N_DATA = I18N_DATA;
